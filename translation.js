window.onload = function () {

  const selector = document.getElementById("lang-selector");
  selector.value = "es"

  function getContainersList(list) {
    var html = '';
    list.forEach(x => {
      html += `<div class='project-role'>${x}</div>`
    });
    return html
  }

  function setLanguage(lang) {

    // Loop through elements and replace text
    document.querySelectorAll("[data-key]").forEach(element => {
      const key = element.getAttribute("data-key");

      if (translations[lang] && translations[lang][key]) {
        //Abilities List
        if (key.includes("list")) {

          var html = "";

          translations[lang][key].forEach(x => {
            html += "<li class='list-item'>" + x + "</li>"
          })

          element.innerHTML = html

          // element.textContent = translations[lang][key];
        }
        //Containers Sets
        else if (key.includes("container")) {
          var html = "";


          translations[lang][key].forEach(x => {
            html += `
            <div class="project">
              <div class="project-header">
                <div class="project-title">
                  <strong>${x['title']}</strong>
                </div>
                <div class="project-year"><strong>${x['year']}</strong></div>
              </div>
              <div class="project-descriptor">
                ${x['description']}
              </div>

              

              ${x['role'] ? getContainersList(x['role']) : ""

              }

              </div>
              `





          })

          element.innerHTML = html

        }
        //Titles        
        else {
          element.textContent = translations[lang][key];
        }

      }
    });
  }
  setLanguage("es");

  selector.addEventListener("change", (event) => {
    setLanguage(event.target.value);

  });
}







